"""Result files, SLO verdicts and the trend table in docs/quality/load.md.

One JSON file per recorded run, ``docs/quality/load-results/<date>-<tool>-<profile>.json``, in the
tool-neutral schema below, so a k6 load run and a Gatling stress run can be read by the same code
and compared on the same table. The trend table is regenerated from those files between markers —
never edited by hand — together with the 2026-08-04 laptop baseline for reference.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import LOAD_DOC, RESULTS_DIR, dump_json, rel  # noqa: E402

RESULT_SCHEMA = "nexus.load.result/v1"
TREND_BEGIN = "<!-- load-trend:begin (generated by scripts/load/run.py; do not edit) -->"
TREND_END = "<!-- load-trend:end -->"
IST = timezone(timedelta(hours=5, minutes=30), "IST")

# deploy/loadtest/README.md, "Measured — 2026-08-04, single laptop, Docker Desktop". Read path =
# /api/accounts?limit=50, /api/signals?limit=50, /api/inbox; 2 replicas x 2 uvicorn workers.
LAPTOP_BASELINE = [
    {"vus": "10", "p50_ms": 22, "p95_ms": 240, "error_rate_pct": 0.00, "rps": 14.2},
    {"vus": "25", "p50_ms": 31, "p95_ms": 470, "error_rate_pct": 0.00, "rps": 33.9},
    {"vus": "50", "p50_ms": 35, "p95_ms": 735, "error_rate_pct": 0.09, "rps": 67.2},
    {"vus": "100", "p50_ms": 304, "p95_ms": 3520, "error_rate_pct": 5.43, "rps": 87.2},
    {"vus": "200 (ramp)", "p50_ms": 412, "p95_ms": 4470, "error_rate_pct": 1.90, "rps": 129.0},
]


def slo_verdict(metrics: dict, slo: dict) -> dict:
    """Grade normalised metrics against the SLO export — the same rule for both tools."""
    api = slo["api"]
    breaches = []

    def over(label: str, value, limit, unit: str) -> None:
        if value is not None and value >= limit:
            breaches.append(f"{label} {value:g}{unit} >= {limit:g}{unit}")

    if not metrics.get("requests"):
        return {"passed": False, "breaches": ["no API requests were measured"], "profile": slo["profile"]}
    over("p95", metrics.get("p95_ms"), api["p95_ms"], " ms")
    over("p99", metrics.get("p99_ms"), api["p99_ms"], " ms")
    over("error rate", metrics.get("error_rate_pct"), api["error_rate_pct"], "%")
    for journey, jm in sorted((metrics.get("by_journey") or {}).items()):
        over(f"{journey} p95", jm.get("p95_ms"), api["p95_ms"], " ms")
    for route, override in sorted((slo.get("routes") or {}).items()):
        name = route.split(" ", 1)[0] + " " + route.split(" ", 1)[1].replace("{", ":").replace("}", "")
        rm = (metrics.get("by_request") or {}).get(name)
        if not rm:
            continue
        if "p95_ms" in override:
            over(f"{name} p95", rm.get("p95_ms"), override["p95_ms"], " ms")
        if "p99_ms" in override:
            over(f"{name} p99", rm.get("p99_ms"), override["p99_ms"], " ms")
        if "error_rate_pct" in override:
            over(f"{name} error rate", rm.get("error_rate_pct"), override["error_rate_pct"], "%")
    return {"passed": not breaches, "breaches": breaches, "profile": slo["profile"],
            "is_fixture": slo.get("is_fixture", False)}


def result_path(summary: dict, results_dir: Path = RESULTS_DIR) -> Path:
    started = datetime.fromisoformat(summary["started_at"]).astimezone(IST)
    stem = f"{started:%Y-%m-%d}-{summary['tool']['name']}-{summary['profile']}"
    path = results_dir / f"{stem}.json"
    if path.exists():
        path = results_dir / f"{stem}-{started:%H%M}.json"
    return path


def write_result(summary: dict, results_dir: Path = RESULTS_DIR) -> Path:
    results_dir.mkdir(parents=True, exist_ok=True)
    path = result_path(summary, results_dir)
    path.write_text(dump_json(summary), encoding="utf-8")
    return path


def load_results(results_dir: Path = RESULTS_DIR) -> list[tuple[Path, dict]]:
    out = []
    for path in sorted(results_dir.glob("*.json")) if results_dir.exists() else []:
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            continue
        if data.get("schema") == RESULT_SCHEMA:
            out.append((path, data))
    return sorted(out, key=lambda pd: pd[1]["started_at"])


def _fmt(value, unit: str = "", digits: int = 0) -> str:
    if value is None:
        return "–"
    return f"{value:,.{digits}f}{unit}"


def _load_label(summary: dict) -> str:
    envelope = summary.get("plan", {}).get("envelope", {})
    measured = summary.get("metrics", {}).get("peak_vus")
    if summary["plan"].get("kind") == "open":
        return f"{envelope.get('peak_users_per_sec', 0):g} users/s (≈{envelope.get('peak_vus')} conc.)"
    return f"{measured or envelope.get('peak_vus')} VUs"


def render_trend(results: list[tuple[Path, dict]], doc_dir: Path) -> str:
    lines = [
        "| Date (IST) | Env | Tool | Profile | Peak load | Requests | Req/s | p50 | p95 | p99 | Errors "
        "| SLO | Δ p95 vs previous | Guard | Result |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    previous: dict[tuple, dict] = {}
    for path, s in results:
        m = s.get("metrics", {})
        key = (s["environment"]["name"], s["tool"]["name"], s["profile"])
        prev = previous.get(key)
        delta = "–"
        if prev and prev.get("p95_ms") and m.get("p95_ms") is not None:
            change = (m["p95_ms"] - prev["p95_ms"]) / prev["p95_ms"] * 100
            delta = f"{change:+.0f}%"
        previous[key] = m
        verdict = s.get("slo_verdict", {})
        slo = "pass" if verdict.get("passed") else "FAIL"
        if verdict.get("is_fixture"):
            slo += " (fixture)"
        guard = s.get("guard", {})
        guard_text = "tripped" if guard.get("aborted") else "–"
        started = datetime.fromisoformat(s["started_at"]).astimezone(IST)
        link = Path(rel(path)).as_posix()
        try:
            link = path.resolve().relative_to(doc_dir.resolve()).as_posix()
        except ValueError:
            pass
        lines.append(
            f"| {started:%Y-%m-%d %H:%M} | {key[0]} | {key[1]} | {key[2]} | {_load_label(s)} "
            f"| {_fmt(m.get('requests'))} | {_fmt(m.get('rps'), digits=1)} | {_fmt(m.get('p50_ms'), ' ms')} "
            f"| {_fmt(m.get('p95_ms'), ' ms')} | {_fmt(m.get('p99_ms'), ' ms')} "
            f"| {_fmt(m.get('error_rate_pct'), '%', 2)} | {slo} | {delta} | {guard_text} | [{path.name}]({link}) |"
        )
    if len(lines) == 2:
        lines.append("| – | – | – | – | no recorded runs yet | | | | | | | | | | |")
    lines += [
        "",
        "Reference — the only earlier measurement, a laptop running Docker Desktop (2026-08-04, "
        "3-endpoint read path, 2 replicas × 2 uvicorn workers, Postgres co-located). Not comparable "
        "row-for-row: different journeys, hardware and pool shape.",
        "",
        "| VUs | p50 | p95 | Errors | Req/s |",
        "|---|---|---|---|---|",
    ]
    for row in LAPTOP_BASELINE:
        lines.append(f"| {row['vus']} | {row['p50_ms']} ms | {row['p95_ms']:,} ms | "
                     f"{row['error_rate_pct']:.2f}% | {row['rps']} |")
    return "\n".join(lines)


def update_trend(doc: Path = LOAD_DOC, results_dir: Path = RESULTS_DIR) -> bool:
    text = doc.read_text(encoding="utf-8")
    start, end = text.find(TREND_BEGIN), text.find(TREND_END)
    if start < 0 or end < start:
        raise ValueError(f"{rel(doc)} is missing the trend markers")
    table = render_trend(load_results(results_dir), doc.parent)
    updated = text[: start + len(TREND_BEGIN)] + "\n" + table + "\n" + text[end:]
    if updated != text:
        doc.write_text(updated, encoding="utf-8")
        return True
    return False
